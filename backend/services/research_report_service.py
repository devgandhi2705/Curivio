# Section builders (internal, exposed for testing)
# ═══════════════════════════════════════════════════════════════════════════════

def _build_executive_summary(research_data: dict, industry_data: dict | None) -> str:
    """
    Synthesise executive summary from existing AI-generated fields.

    Pure text composition — no AI call.  Combines research_summary,
    top strategic implication, optional industry context, and a
    confidence-calibration sentence.
    """
    parts: list[str] = []

    summary = research_data.get("research_summary", "").strip()
    if summary:
        parts.append(summary)

    implications = research_data.get("strategic_implications", [])
    if implications:
        cleaned = re.sub(r"^Implication \d+\s*[—\-]\s*[^:]+:\s*", "", implications[0]).strip()
        if cleaned:
            parts.append(f"Strategically, {cleaned}")

    if industry_data:
        trend_summary = industry_data.get("trend_summary", "").strip()
        if trend_summary:
            parts.append(f"Industry context: {trend_summary}")

    confidence_note = {
        "high":   "This analysis is supported by multiple converging sources.",
        "medium": "This analysis reflects mixed signals from available sources.",
        "low":    "This analysis is based on limited source material and should be treated as preliminary.",
    }.get(research_data.get("confidence_level", "medium"), "")
    if confidence_note:
        parts.append(confidence_note)

    return " ".join(parts) if parts else "No summary available."


def _extract_key_findings(research_data: dict) -> list[str]:
    """
    Return key findings list; augments with viewpoint stances when sparse.
    """
    findings = list(research_data.get("key_findings", []))

    if len(findings) < 3:
        for vp in research_data.get("viewpoint_comparison", [])[:2]:
            stance = vp.get("stance", "").strip()
            label  = vp.get("perspective", "")
            if stance:
                findings.append(f"[{label}] {stance}" if label else stance)

    return findings[:8]


def _build_trend_analysis(research_data: dict) -> dict:
    trends   = research_data.get("trends_identified", [])
    momentum = _score_momentum(trends + [research_data.get("research_summary", "")])
    return {"trends": trends, "momentum": momentum}


def _extract_opportunities(research_data: dict, industry_data: dict | None) -> list[str]:
    opps: list[str] = []

    for imp in research_data.get("strategic_implications", [])[:3]:
        cleaned = re.sub(r"^Implication \d+\s*[—\-]\s*[^:]+:\s*", "", imp).strip()
        if cleaned:
            opps.append(cleaned)

    for app in research_data.get("practical_applications", [])[:3]:
        cleaned = re.sub(r"^[Aa]pplication \d+:?\s*", "", app).strip()
        if cleaned and cleaned not in opps:
            opps.append(cleaned)

    if industry_data:
        for opp in industry_data.get("emerging_opportunities", [])[:2]:
            label = opp.get("opportunity", "").strip()
            if label and label not in opps:
                opps.append(label)

    return opps[:8]


def _extract_risks(research_data: dict) -> list[str]:
    risks: list[str] = []

    for tradeoff in research_data.get("tradeoffs", [])[:3]:
        dimension = tradeoff.get("dimension", "").strip()
        verdict   = tradeoff.get("verdict", "").strip()
        if dimension:
            entry = f"{dimension}: {verdict}" if verdict else dimension
            risks.append(entry)

    for q in research_data.get("open_questions", [])[:3]:
        cleaned = re.sub(r"^Question \d+\s*[—\-]\s*[^:]+:\s*", "", q).strip()
        if cleaned:
            risks.append(f"Unresolved: {cleaned}")

    return risks[:6]


def _build_resource_list(research_data: dict) -> list[dict]:
    seen: set[str] = set()
    resources: list[dict] = []

    for url in research_data.get("sources", []):
        if not url or url in seen:
            continue
        seen.add(url)
        resources.append({"url": url, "type": _classify_url(url)})

    resources.sort(key=lambda r: _TIER_ORDER.get(r["type"], 5))
    return resources[:10]


# ═══════════════════════════════════════════════════════════════════════════════
# Helpers
# ═══════════════════════════════════════════════════════════════════════════════

def _score_momentum(texts: list[str]) -> str:
    combined = " ".join(texts).lower()
    words    = set(re.sub(r"[^\w\s]", " ", combined).split())
    accel    = len(words & _ACCELERATING_WORDS)
    decline  = len(words & _DECLINING_WORDS)
    if accel > decline + 1:
        return "accelerating"
    if decline > accel + 1:
        return "declining"
    return "stable"


def _confidence_label(level: str) -> str:
    return {"high": "High ✓", "medium": "Medium", "low": "Low ⚠"}.get(level, "Medium")


def _fmt_date(iso: str) -> str:
    try:
        dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return dt.strftime("%B %d, %Y")
    except Exception:
        return iso[:10] if len(iso) >= 10 else "Unknown"


def _url_label(url: str) -> str:
    try:
        parsed = urlparse(url)
        netloc = parsed.netloc.removeprefix("www.")
        last   = parsed.path.rstrip("/").split("/")[-1]
        label  = last.replace("-", " ").replace("_", " ").strip()
        return f"{netloc} — {label}" if label else netloc
    except Exception:
        return url[:60]
