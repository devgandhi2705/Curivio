"""
Retrieval query expansion engine.

Transforms a single user topic into a ranked list of Tavily-optimised search
queries without any LLM calls.  Queries are generated by combining the topic
with domain-specific angles (authority, trend, implementation, tutorial, etc.)
drawn from retrieval_config.py trusted-source data.

Replaces the purely educational ``topic_expansion_service`` pattern for the
retrieval path.  ``topic_expansion_service`` (learning graph: prerequisites,
related_topics, progressions) is preserved separately for the UI/chat layer.

Design constraints
------------------
- Zero I/O — pure string operations, no DB, no API calls.
- Mode-aware limits: chat 1–2, feed 2–4, deep_research 4–6.
- Retrieval-first: every query angle is designed to surface documents, not
  explain concepts.
- Trusted-source preference: authority angles embed known source names so
  Tavily's ranking surfaces them even without ``include_domains``.

Public API
----------
expand_queries(topic, mode)           → ExpansionResult
get_query_strings(topic, mode)        → list[str]   convenience wrapper
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# ── Mode query-count limits ───────────────────────────────────────────────────

