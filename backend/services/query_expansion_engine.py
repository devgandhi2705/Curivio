# ── Output types ──────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class ExpandedQuery:
    text:        str
    angle:       str             # angle label from _QueryAngle
    source_hint: str | None      # trusted domain this query targets (if any)
    priority:    int


@dataclass
class ExpansionResult:
    topic:      str
    domain_key: str
    mode:       str
    queries:    list[ExpandedQuery]  # ordered by priority, length = mode limit

    def query_strings(self) -> list[str]:
        """Return just the query text strings, preserving priority order."""
        return [q.text for q in self.queries]

    def authority_queries(self) -> list[ExpandedQuery]:
        """Return only queries targeting a known trusted source."""
        return [q for q in self.queries if q.source_hint]


# ── Topic normalisation ───────────────────────────────────────────────────────

# Connector words that add noise without improving retrieval precision.
_CONNECTORS = re.compile(
    r"\b(in|for|the|of|and|or|with|using|via|by|from|to|at|a|an|about)\b",
    re.IGNORECASE,
)


def _normalize(topic: str) -> str:
    """
    Strip connector words and collapse whitespace.

    "AI in manufacturing" → "AI manufacturing"
    "deep learning for healthcare" → "deep learning healthcare"
    """
    cleaned = _CONNECTORS.sub(" ", topic.strip())
    return re.sub(r"\s{2,}", " ", cleaned).strip()


# ── Domain resolution ─────────────────────────────────────────────────────────

def _resolve_domain(topic: str) -> str:
    """
    Classify topic into a retrieval_config key without importing the full
    domain_classifier (avoids circular dependency at module load time).
    """
    from .retrieval_router import multi_classify   # deferred
    return multi_classify(topic).primary.domain_key


# ── Core expansion logic ──────────────────────────────────────────────────────

def expand_queries(topic: str, mode: str = "chat") -> ExpansionResult:
    """
    Expand a topic into a ranked list of Tavily-optimised retrieval queries.

    Parameters
    ----------
    topic   User query or topic string (any length).
    mode    "chat" | "feed" | "deep_research"  — controls query budget.

    Returns
    -------
    ExpansionResult whose ``.queries`` list is at most ``_MODE_LIMITS[mode]``
    entries, ordered by priority (most important first).

    The function never raises — a minimal one-query result is always returned.
    """
    limit      = _MODE_LIMITS.get(mode, _DEFAULT_LIMIT)
    domain_key = _resolve_domain(topic)
    base       = _normalize(topic)

    angles = _DOMAIN_ANGLES.get(domain_key, _DOMAIN_ANGLES["default"])
    # Sort by priority so the budget truncation always keeps the best queries.
    sorted_angles = sorted(angles, key=lambda a: a.priority)

    expanded: list[ExpandedQuery] = []
    seen_texts: set[str] = set()

    for angle in sorted_angles:
        if len(expanded) >= limit:
            break

        try:
            text = angle.template.format(topic=topic, base=base).strip()
        except KeyError:
            text = angle.template.replace("{topic}", topic).replace("{base}", base).strip()

        # Deduplicate — can happen when topic == base
        norm_text = re.sub(r"\s+", " ", text.lower())
        if norm_text in seen_texts:
            continue
        seen_texts.add(norm_text)

        expanded.append(ExpandedQuery(
            text        = text,
            angle       = angle.angle,
            source_hint = angle.source_hint,
            priority    = angle.priority,
        ))

    # Safety: always return at least the raw topic
    if not expanded:
        expanded = [ExpandedQuery(text=topic, angle="primary", source_hint=None, priority=1)]

    return ExpansionResult(
        topic      = topic,
        domain_key = domain_key,
        mode       = mode,
        queries    = expanded,
    )


# ── Convenience accessor ──────────────────────────────────────────────────────

def get_query_strings(topic: str, mode: str = "chat") -> list[str]:
    """
    Return just the query strings for a topic and mode.

    Convenience wrapper around ``expand_queries`` for callers that don't
    need the full ``ExpansionResult`` metadata.
    """
    return expand_queries(topic, mode).query_strings()
