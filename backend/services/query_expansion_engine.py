# ── Query angle descriptor ────────────────────────────────────────────────────

@dataclass(frozen=True)
class _QueryAngle:
    """
    Template for one retrieval angle.

    ``template``    — Python format string with a ``{topic}`` placeholder.
                      May also use ``{base}`` (connector-stripped form).
    ``angle``       — human label: "primary" | "authority" | "trend" |
                      "implementation" | "tutorial" | "comparison" | "report"
    ``priority``    — lower = more important; determines selection order within
                      a mode's query budget.
    ``source_hint`` — optional trusted domain this query targets (metadata only;
                      the router applies include_domains separately).
    """
    template:    str
    angle:       str
    priority:    int
    source_hint: str | None = None


